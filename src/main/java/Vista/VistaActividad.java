public void mostrarPregunta(String titulo, String pregunta, int[] opciones, int actual, int total) {
    lblTitulo.setText(titulo);
    lblPregunta.setText(pregunta);
    lblProgreso.setText("Pregunta " + actual + "/" + total);
    lblResultado.setText(" ");
    btnOp1.setText(String.valueOf(opciones[0]));
    btnOp2.setText(String.valueOf(opciones[1]));
    btnOp3.setText(String.valueOf(opciones[2]));
    btnOp4.setText(String.valueOf(opciones[3]));
}

public int obtenerOpcion(int numero) {
    switch (numero) {
        case 1: return Integer.parseInt(btnOp1.getText());
        case 2: return Integer.parseInt(btnOp2.getText());
        case 3: return Integer.parseInt(btnOp3.getText());
        default: return Integer.parseInt(btnOp4.getText());
    }
}

public void mostrarResultado(String mensaje) {
    lblResultado.setText(mensaje); 
}
